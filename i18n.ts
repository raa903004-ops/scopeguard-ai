export type Message = keyof typeof ru;
export type Translate = (message: Message) => string;

const en: Translate = (message) => message;
const russian: Translate = (message) => ru[message];
export const translate = (language: Language): Translate =>
  language === "ru" ? russian : en;

export const locale = { en: "en-US", ru: "ru-RU" };

export class MessageError extends Error {
  readonly key: Message;
  readonly detail?: string;

  constructor(key: Message, detail?: string) {
    super(key);
    this.key = key;
    this.detail = detail;
  }
}

export function interpolate(
  message: string,
  values: Record<string, string>,
): string {
  return message.replace(
    /\{(\w+)\}/g,
    (placeholder, key: string) => values[key] ?? placeholder,
  );
}
